# caractères hors Latin-1 placés dans des codes libres (0x80-0x9F)
SPECIAL = {"€": 0x80, "←": 0x81, "→": 0x82, "↑": 0x83, "↓": 0x84}

ACCENTS = {
    "acute": {1: "....##.", 2: "...##.."},
    "grave": {1: ".##....", 2: "..##..."},
    "circ":  {1: "..###..", 2: ".##.##."},
    "uml":   {2: ".##.##."},
}
COMPOSE = {
    "à": ("a", "grave"), "á": ("a", "acute"), "â": ("a", "circ"), "ä": ("a", "uml"),
    "è": ("e", "grave"), "é": ("e", "acute"), "ê": ("e", "circ"), "ë": ("e", "uml"),
    "ì": ("i", "grave"), "í": ("i", "acute"), "î": ("i", "circ"), "ï": ("i", "uml"),
    "ò": ("o", "grave"), "ó": ("o", "acute"), "ô": ("o", "circ"), "ö": ("o", "uml"),
    "ù": ("u", "grave"), "ú": ("u", "acute"), "û": ("u", "circ"), "ü": ("u", "uml"),
    "ÿ": ("y", "uml"),
}
# Majuscules accentuées : l'accent est placé dans les lignes 0-1 de la cellule.
COMPOSE_UPPER = {
    "À": ("A", "grave"), "Â": ("A", "circ"), "Ä": ("A", "uml"),
    "È": ("E", "grave"), "É": ("E", "acute"), "Ê": ("E", "circ"), "Ë": ("E", "uml"),
    "Î": ("I", "circ"), "Ï": ("I", "uml"), "Ô": ("O", "circ"), "Ö": ("O", "uml"),
    "Ù": ("U", "grave"), "Û": ("U", "circ"), "Ü": ("U", "uml"),
}
CEDILLA = {10: "...##..", 11: ".###..."}

ROW_OFFSET = 2  # ligne 0 du dessin = ligne 2 de la cellule


def code_of(ch):
    if ch in SPECIAL:
        return SPECIAL[ch]
    c = ord(ch)
    if c > 255:
        raise ValueError(f"caractère hors Latin-1 : {ch!r}")
    return c


def parse_art():
    glyphs = {}
    cur = None
    for raw in ART.splitlines():
        line = raw.rstrip()
        if not line:
            continue
        if line.startswith("@"):
            name = line[1:]
            cur = " " if name == "space" else name
            if len(cur) != 1:
                raise ValueError(f"nom de glyphe invalide : {line!r}")
            glyphs[cur] = {}
            continue
        rows, pat = line.split(" ", 1)
        if len(pat) != 7 or set(pat) - set(".#"):
            raise ValueError(f"motif invalide pour {cur!r} : {line!r}")
        if "-" in rows:
            a, b = (int(v) for v in rows.split("-"))
        else:
            a = b = int(rows)
        for r in range(a, b + 1):
            if not 0 <= r <= 12:
                raise ValueError(f"ligne hors limites pour {cur!r} : {line!r}")
            glyphs[cur][r] = pat
    return glyphs


def to_cell(art_rows):
    cell = [0] * 16
    for r, pat in art_rows.items():
        v = 0
        for i, ch in enumerate(pat):
            if ch == "#":
                v |= 0x80 >> i
        cell[r + ROW_OFFSET] = v
    return cell


def build():
    glyphs = parse_art()
    cells = {}
    for ch, rows in glyphs.items():
        cells[code_of(ch)] = to_cell(rows)
    for ch, (base, acc) in COMPOSE.items():
        rows = {r: p for r, p in glyphs[base].items() if r >= 3}
        rows.update(ACCENTS[acc])
        cells[code_of(ch)] = to_cell(rows)
    for ch, (base, acc) in COMPOSE_UPPER.items():
        cell = to_cell(glyphs[base])
        for r, pat in ACCENTS[acc].items():
            v = 0
            for i, c in enumerate(pat):
                if c == "#":
                    v |= 0x80 >> i
            cell[r - 1] = v
        cells[code_of(ch)] = cell
    c_rows = {r: p for r, p in glyphs["c"].items()}
    c_rows.update(CEDILLA)
    cells[code_of("ç")] = to_cell(c_rows)
    C_rows = {r: p for r, p in glyphs["C"].items()}
    C_rows.update(CEDILLA)
    cells[code_of("Ç")] = to_cell(C_rows)

    box = to_cell({1: "#######", **{r: "#.....#" for r in range(2, 9)}, 9: "#######"})
    table = []
    for code in range(256):
        if code in cells:
            table.append(cells[code])
        elif code < 32 or code == 127:
            table.append([0] * 16)
        else:
            table.append(box)
    return table


def write_c(table, path):
    out = ["/* Police bitmap 8x16 de TitanOs - générée par tools/fontgen.py, ne pas modifier. */",
           "#include \"font.h\"", "", "const uint8_t font8x16[256][16] = {"]
    for code, cell in enumerate(table):
        out.append("    { " + ", ".join(f"0x{v:02x}" for v in cell) + f" }}, /* 0x{code:02x} */")
    out.append("};")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def write_png(path, w, h, pixels):
    raw = b"".join(b"\x00" + bytes(pixels[y * w:(y + 1) * w]) for y in range(h))
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0))
    data += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(data)


def preview(table, path, scale=3):
    cols, rows = 16, 14  # codes 32..255
    w, h = cols * 8 * scale, rows * 16 * scale
    px = [40] * (w * h)
    for idx, code in enumerate(range(32, 256)):
        gx, gy = (idx % cols) * 8 * scale, (idx // cols) * 16 * scale
        for r in range(16):
            bits = table[code][r]
            for c in range(8):
                on = bits & (0x80 >> c)
                for sy in range(scale):
                    for sx in range(scale):
                        px[(gy + r * scale + sy) * w + gx + c * scale + sx] = 255 if on else (60 if (c == 7 or r == 15) else 30)
    write_png(path, w, h, px)


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    table = build()
    os.makedirs(os.path.join(root, "build", "gen"), exist_ok=True)
    write_c(table, os.path.join(root, "build", "gen", "font8x16.c"))
    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        preview(table, out)
        print("aperçu :", out)
    print("build/gen/font8x16.c généré")
